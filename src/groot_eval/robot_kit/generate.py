"""Generators: every per-robot config written from the one descriptor.

========================  =================================================================
File                      Used by
========================  =================================================================
``modality.json``         LeRobot dataset ``meta/``; GR00T fine-tuning and the policy server
``gr00t_modality.py``     GR00T fine-tuning: modality config (keys, delta indices, action reps)
``conversion.yaml``       ``groot-twin convert-check``: raw HDF5 logs to LeRobot v2
``isaaclab_robot.py``     Isaac Lab: ``ArticulationCfg`` with one actuator group per joint group
``mujoco_actuators.xml``  MuJoCo: position actuators and joint sensors to include in the robot MJCF
``ros2_topics.yaml``      ``groot-robot bridge`` / ``rig``: state, command and camera topics
``logging_schema.yaml``   policy / action / joint logging with the joint names filled in
``robot_profile.yaml``    ``groot-eval transfer --robot``: limits the hardware accepts
``MANIFEST.json``         descriptor hash and the file list, so a stale copy can be spotted
========================  =================================================================

The Isaac Lab and GR00T files follow those projects' public config shapes;
their APIs move between releases, so each file names the version it was
written against at the top. Check it against your install.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import yaml

from groot_eval.robot_kit.descriptor import Descriptor

GR00T_TARGET = "Isaac-GR00T N1.6 modality config layout"
ISAACLAB_TARGET = "Isaac Lab 2.x / 3.0 ArticulationCfg + ImplicitActuatorCfg"
LOG_FIELDS = {
    "policy": ["t", "step", "model_id", "checkpoint_hash", "instruction", "obs_hash", "action_chunk", "latency_ms"],
    "action": ["t", "policy_step", "commanded", "applied", "clipped"],
    "joint": ["t", "position", "velocity", "effort"],
}


def descriptor_hash(desc: Descriptor) -> str:
    blob = json.dumps(desc.to_dict(), sort_keys=True, default=str).encode()
    return hashlib.sha256(blob).hexdigest()[:16]


# -- GR00T -----------------------------------------------------------------------------------------
def modality_json(desc: Descriptor) -> dict[str, Any]:
    """LeRobot ``meta/modality.json``: start/end of each group in ``observation.state`` and ``action``."""
    state: dict[str, Any] = {}
    action: dict[str, Any] = {}
    for g, sl in desc.slices().items():
        grp = desc.group(g)
        state[g] = {"start": sl.start, "end": sl.stop}
        action[g] = {"start": sl.start, "end": sl.stop}
        if grp.action == "relative":
            action[g]["absolute"] = False
    video = {c.name: {"original_key": f"observation.images.{c.name}"} for c in desc.cameras}
    return {"state": state, "action": action, "video": video,
            "annotation": {desc.language_key.removeprefix("annotation."): {}}}


def gr00t_modality_py(desc: Descriptor) -> str:
    groups = [g.name for g in desc.groups]
    cams = [c.name for c in desc.cameras]
    reps = []
    for g in desc.groups:
        rep = "RELATIVE" if g.action == "relative" else "ABSOLUTE"
        reps.append(f"        ActionConfig(rep=ActionRepresentation.{rep}, type=ActionType.NON_EEF, "
                    f"format=ActionFormat.DEFAULT),  # {g.name}")
    lines = [
        f'"""GR00T modality config for {desc.name}. Generated by groot-robot kit generate; do not edit by hand.',
        "",
        f"Written against: {GR00T_TARGET}. Check the import paths against your Isaac-GR00T checkout.",
        f"Descriptor hash: {descriptor_hash(desc)}",
        '"""',
        "",
        "from gr00t.configs.data.embodiment_configs import register_modality_config",
        "from gr00t.data.embodiment_tags import EmbodimentTag",
        "from gr00t.data.types import ActionConfig, ActionFormat, ActionRepresentation, ActionType, ModalityConfig",
        "",
        f"STATE_KEYS = {groups!r}",
        f"ACTION_KEYS = {groups!r}",
        f"VIDEO_KEYS = {cams!r}",
        f"ACTION_HORIZON = {desc.timing.action_horizon}",
        "",
        "modality_config = {",
        '    "video": ModalityConfig(delta_indices=[0], modality_keys=VIDEO_KEYS),',
        '    "state": ModalityConfig(delta_indices=[0], modality_keys=STATE_KEYS),',
        '    "action": ModalityConfig(',
        "        delta_indices=list(range(ACTION_HORIZON)),",
        "        modality_keys=ACTION_KEYS,",
        "        action_configs=[",
        *reps,
        "        ],",
        "    ),",
        f'    "language": ModalityConfig(delta_indices=[0], modality_keys=[{desc.language_key!r}]),',
        "}",
        "",
        "register_modality_config(modality_config, embodiment_tag=EmbodimentTag.NEW_EMBODIMENT)",
        "",
    ]
    return "\n".join(lines)


def conversion_yaml(desc: Descriptor) -> dict[str, Any]:
    """Starting point for ``configs/conversion``: HDF5 keys are guesses named after the groups."""
    return {
        "mapping": {
            "episodes": "data/demo_*",
            "fps": desc.timing.control_hz,
            "task_attr": "task",
            "success_attr": "success",
            "state": [{"key": f"obs/{g.name}_pos", "modality": g.name} for g in desc.groups],
            "action": [{"key": f"actions/{g.name}", "modality": g.name} for g in desc.groups],
            "video": {c.name: f"obs/{c.name}_rgb" for c in desc.cameras},
            "scalars": {},
            "ignore": [],
        },
        "gates": {
            "C0_inventory": {"lost_is_error": True},
            "C1_timing": {"max_fps_rel_error": 0.01, "max_period_jitter_frac": 0.1},
            "C2_actuator": {"max_rel_error": 1.0e-4, "min_snr_db": 60},
            "C3_visual": {"min_psnr_mean": 35, "min_psnr_p5": 30, "min_ssim_mean": 0.95},
            "C4_metadata": {},
        },
    }


# -- simulators ------------------------------------------------------------------------------------
def _regex(names: list[str]) -> str:
    return "|".join(names)


def isaaclab_robot_py(desc: Descriptor) -> str:
    asset = desc.assets.get("usd") or desc.assets.get("urdf") or "<path to USD>"
    spawn = ("sim_utils.UsdFileCfg(usd_path=ASSET)" if desc.assets.get("usd")
             else "sim_utils.UrdfFileCfg(asset_path=ASSET, fix_base=False)")
    act = []
    for g in desc.groups:
        names = [j.name for j in g.joints]
        def per(attr: str, names: list[str] = names, g: Any = g) -> str:
            vals = {j.name: getattr(j, attr) for j in g.joints if getattr(j, attr) is not None}
            return repr(vals) if vals else "None"
        act.append(f'        "{g.name}": ImplicitActuatorCfg(\n'
                   f'            joint_names_expr=[{_regex(names)!r}],\n'
                   f'            stiffness={per("stiffness")},\n'
                   f'            damping={per("damping")},\n'
                   f'            effort_limit_sim={per("effort_limit")},\n'
                   f'            velocity_limit_sim={per("max_velocity")},\n'
                   f"        ),")
    init = {j.name: round((j.limits[0] + j.limits[1]) / 2, 4) if not (j.limits[0] <= 0 <= j.limits[1]) else 0.0
            for j in desc.joints}
    return "\n".join([
        f'"""Isaac Lab articulation for {desc.name}. Generated by groot-robot kit generate; do not edit by hand.',
        "",
        f"Written against: {ISAACLAB_TARGET}. Swap an ImplicitActuatorCfg for",
        "groot_eval.actuators.isaaclab_actuator.build_actuator(...) to use the wear-aware drive model",
        "(see docs/actuators.md). Isaac Lab 3.0 orders quaternions XYZW;",
        f"this descriptor's frames use {desc.quat_order.upper()}.",
        f"Descriptor hash: {descriptor_hash(desc)}",
        '"""',
        "",
        "import isaaclab.sim as sim_utils",
        "from isaaclab.actuators import ImplicitActuatorCfg",
        "from isaaclab.assets import ArticulationCfg",
        "",
        f"ASSET = {asset!r}",
        f"JOINT_ORDER = {desc.joint_names!r}  # model order; Isaac Lab's own order may differ, map by name",
        "",
        f"{desc.name.upper().replace('-', '_')}_CFG = ArticulationCfg(",
        f"    spawn={spawn},",
        f"    init_state=ArticulationCfg.InitialStateCfg(joint_pos={init!r}),",
        "    actuators={",
        *act,
        "    },",
        ")",
        "",
    ])


def mujoco_actuators_xml(desc: Descriptor) -> str:
    """Position actuators and joint sensors, to ``<include>`` in the robot's MJCF."""
    rows = ["<mujoco>", "  <actuator>"]
    for j in desc.joints:
        kp = j.stiffness if j.stiffness is not None else 100.0
        kv = f' kv="{j.damping}"' if j.damping is not None else ""
        force = f' forcerange="{-j.effort_limit} {j.effort_limit}"' if j.effort_limit else ""
        rows.append(f'    <position name="{j.name}" joint="{j.name}" kp="{kp}"{kv} '
                    f'ctrlrange="{j.limits[0]} {j.limits[1]}"{force}/>')
    rows += ["  </actuator>", "  <sensor>"]
    rows += [f'    <jointpos name="{j.name}_pos" joint="{j.name}"/>' for j in desc.joints]
    rows += ["  </sensor>", "</mujoco>", ""]
    return "\n".join(rows)


def mujoco_stub_xml(desc: Descriptor, kp: float = 10.0, kv: float = 1.0) -> str:
    """A standalone model with one hinge per joint on its own small link: no geometry from
    the real robot, but the same joint names, order, limits and actuators. Used to test the
    generated adapters and the jog test before the real model exists."""
    bodies = []
    for i, j in enumerate(desc.joints):
        bodies.append(
            f'    <body name="link_{j.name}" pos="{i * 0.3} 0 0.5">\n'
            f'      <joint name="{j.name}" type="hinge" axis="0 1 0" range="{j.limits[0]} {j.limits[1]}" '
            f'limited="true" damping="0.5"/>\n'
            f'      <geom type="capsule" fromto="0 0 0 0.1 0 0" size="0.02" mass="1.0"/>\n'
            f"    </body>")
    acts = [f'    <position name="{j.name}" joint="{j.name}" kp="{kp}" kv="{kv}"/>' for j in desc.joints]
    return "\n".join([
        f'<mujoco model="{desc.name}_stub">',
        '  <compiler angle="radian"/>',
        '  <option timestep="0.002" gravity="0 0 0" integrator="implicitfast"/>',
        "  <worldbody>", *bodies, "  </worldbody>",
        "  <actuator>", *acts, "  </actuator>",
        "</mujoco>", ""])


# -- robot side ------------------------------------------------------------------------------------
def ros2_topics(desc: Descriptor) -> dict[str, Any]:
    ns = f"/{desc.name}"
    groups = {}
    for g in desc.groups:
        groups[g.name] = {
            "joints": [j.name for j in g.joints],
            "state_topic": g.state_topic or f"{ns}/{g.name}/joint_states",
            "state_type": "sensor_msgs/msg/JointState",
            "command_topic": g.command_topic or f"{ns}/{g.name}/command",
            "command_type": "trajectory_msgs/msg/JointTrajectory",
        }
    cams = {c.name: {"topic": c.topic or f"{ns}/camera/{c.name}/image_raw", "type": "sensor_msgs/msg/Image",
                     "encoding": "rgb8" if c.color_order == "rgb" else "bgr8", "fps": c.fps}
            for c in desc.cameras}
    return {"robot": desc.name, "control_hz": desc.timing.control_hz, "groups": groups, "cameras": cams,
            "note": "Generated defaults. Replace topic names with the driver's real ones; joint names must match."}


def logging_schema(desc: Descriptor) -> dict[str, Any]:
    t = desc.timing
    return {
        "robot": desc.name,
        "joint_order": desc.joint_names,
        "policy": {"rate_hz": t.policy_hz, "fields": LOG_FIELDS["policy"],
                   "action_chunk_shape": [t.action_horizon, desc.dim]},
        "action": {"rate_hz": t.control_hz, "fields": LOG_FIELDS["action"], "width": desc.dim},
        "joint": {"rate_hz": max(t.control_hz, 50.0), "fields": LOG_FIELDS["joint"], "width": desc.dim},
        "stamps": ["checkpoint", "deployed_build", "firmware", "gains", "robot_profile", "twin_assets"],
    }


def robot_profile(desc: Descriptor) -> dict[str, Any]:
    """The ``configs/robots`` limits file read by ``groot-eval transfer --robot``."""
    limits = {g.name: [list(j.limits) if g.kind != "gripper" else [0.0, 1.0] for j in g.joints]
              for g in desc.groups}
    vel = {g.name: [[-float(j.max_velocity or 0.0), float(j.max_velocity or 0.0)] for j in g.joints]
           for g in desc.groups if all(j.max_velocity for j in g.joints)}
    out: dict[str, Any] = {"name": desc.name, "embodiment": desc.embodiment_tag,
                           "control_hz": desc.timing.control_hz, "state_limits": {**limits}}
    if vel:
        out["velocity_limits"] = vel
    if desc.safety.max_action_rate:
        out["max_action_rate"] = desc.safety.max_action_rate
    if desc.cameras:
        out["camera"] = {c.name: {"height": c.height, "width": c.width} for c in desc.cameras}
    return out


# -- all -------------------------------------------------------------------------------------------
def render_all(desc: Descriptor) -> dict[str, str]:
    def y(d: Any) -> str:
        return yaml.safe_dump(d, sort_keys=False, width=120)

    files = {
        "modality.json": json.dumps(modality_json(desc), indent=2) + "\n",
        "gr00t_modality.py": gr00t_modality_py(desc),
        "conversion.yaml": y(conversion_yaml(desc)),
        "isaaclab_robot.py": isaaclab_robot_py(desc),
        "mujoco_actuators.xml": mujoco_actuators_xml(desc),
        "mujoco_stub.xml": mujoco_stub_xml(desc),
        "ros2_topics.yaml": y(ros2_topics(desc)),
        "logging_schema.yaml": y(logging_schema(desc)),
        "robot_profile.yaml": y(robot_profile(desc)),
    }
    files["MANIFEST.json"] = json.dumps({"robot": desc.name, "descriptor_hash": descriptor_hash(desc),
                                         "files": sorted(files)}, indent=2) + "\n"
    return files


def write_all(desc: Descriptor, out_dir: str | Path) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, text in render_all(desc).items():
        p = out / name
        p.write_text(text, encoding="utf-8")
        paths.append(p)
    return paths


def is_stale(desc: Descriptor, out_dir: str | Path) -> bool:
    """True if the generated files were made from a different descriptor."""
    m = Path(out_dir) / "MANIFEST.json"
    if not m.exists():
        return True
    return bool(json.loads(m.read_text(encoding="utf-8")).get("descriptor_hash") != descriptor_hash(desc))
